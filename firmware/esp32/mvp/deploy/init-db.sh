#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" -v app_password="$APP_DB_PASSWORD" <<'SQL'
CREATE ROLE ogpass LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'app_password';
GRANT CONNECT ON DATABASE ogpass TO ogpass;
GRANT USAGE ON SCHEMA public TO ogpass;
ALTER DEFAULT PRIVILEGES FOR ROLE ogpass_owner IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ogpass;
ALTER DEFAULT PRIVILEGES FOR ROLE ogpass_owner IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO ogpass;
SQL
